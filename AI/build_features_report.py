"""Build the feature-engineering and AgriFusion integration report."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

BASE = Path(__file__).resolve().parent
MR = BASE / "model_ready"
REPORT = BASE / "_report"
OUT_PATH = BASE / "NASA_Features_and_AgriFusion_Report.docx"

INK = RGBColor(0x0B, 0x0B, 0x0B)
MUTED = RGBColor(0x52, 0x51, 0x4E)


def shade(cell, hex_fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def add_table(doc, headers, rows, widths=None, font_size=8.5):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, text in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(str(text))
        run.bold = True
        run.font.size = Pt(font_size)
        shade(cell, "EFEEE9")
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(value))
            run.font.size = Pt(font_size)
    if widths:
        total = sum(widths)
        scaled = [w * 16.4 / total for w in widths]
        table.autofit = False
        for row in table.rows:
            for i, w in enumerate(scaled):
                row.cells[i].width = Cm(w)
    return table


def caption(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.italic = True
    r.font.size = Pt(8.5)
    r.font.color.rgb = MUTED
    p.paragraph_format.space_after = Pt(10)


def body(doc, text, lead=None):
    p = doc.add_paragraph()
    if lead:
        r = p.add_run(lead)
        r.bold = True
    p.add_run(text)
    return p


def bullet(doc, text, lead=None):
    p = doc.add_paragraph(style="List Bullet")
    if lead:
        r = p.add_run(lead)
        r.bold = True
    p.add_run(text)
    p.paragraph_format.space_after = Pt(3)
    return p


def main() -> int:
    baseline = json.loads((MR / "baseline_results.json").read_text(encoding="utf-8"))
    screening = json.loads((REPORT / "feature_screening.json").read_text(encoding="utf-8"))
    fdict = pd.read_csv(MR / "feature_dictionary.csv")
    daily_q = pd.read_csv(MR / "data_quality_report.csv")
    daily_rows = int(daily_q[(daily_q.table == "daily")].rows.iloc[0])
    monthly_rows = int(daily_q[(daily_q.table == "monthly")].rows.iloc[0])
    n_features = int((fdict.is_target == 0).sum())
    daily_cols = int((fdict.table == "daily").sum())
    monthly_cols = int((fdict.table == "monthly").sum())

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)
    style.font.color.rgb = INK
    style.paragraph_format.space_after = Pt(6)
    style.paragraph_format.line_spacing = 1.12
    for section in doc.sections:
        section.page_height = Cm(29.7)
        section.page_width = Cm(21.0)
        section.left_margin = Cm(2.2)
        section.right_margin = Cm(2.2)
        section.top_margin = Cm(2.0)
        section.bottom_margin = Cm(2.0)

    t = doc.add_paragraph().add_run("From Raw NASA Feeds to a Prediction Pipeline")
    t.bold = True
    t.font.size = Pt(22)
    sub = doc.add_paragraph().add_run(
        "Feature engineering, model-readiness, and where the data plugs into AgriFusionBD"
    )
    sub.font.size = Pt(12)
    sub.font.color.rgb = MUTED
    meta = doc.add_paragraph().add_run(
        "11 November 2026. Every number in this report is generated by the scripts named in section 10 "
        "and stored in Data/model_ready/ and Data/_report/."
    )
    meta.font.size = Pt(9)
    meta.font.color.rgb = MUTED

    # 1 summary
    doc.add_heading("1. Summary", level=1)
    body(
        doc,
        f"The six NASA datasets were turned into two analysis tables: a daily panel of "
        f"{daily_rows:,} rows (7 regions x 1,759 days) and a monthly panel of {monthly_rows} rows, "
        f"carrying {n_features} documented features. Every feature is computed only from information "
        "available at the end of its own day, every target is an explicit forward shift, and nothing "
        "is zero-filled.",
    )
    body(
        doc,
        "The tables predict what should be predictable and refuse what should not. Next-day soil "
        f"moisture reaches R2 = {baseline['soil_moisture_next_day']['gradient_boosting']['r2']:.2f} and "
        f"next-day reference ET0 R2 = {baseline['et0_next_day']['ridge']['r2']:.2f}, both well above a "
        "persistence baseline. Next-day rainfall stays near zero: a single point, one day ahead, from "
        "these predictors, is not a solved problem and the pipeline does not pretend otherwise.",
    )
    body(
        doc,
        "One serious defect had to be fixed before any of this was trustworthy: the existing POWER "
        "downloads carry precipitation multiplied by exactly 24. Corrected copies are in "
        "Data/power_corrected/; the originals were left untouched.",
    )

    # 2 defect
    doc.add_heading("2. A defect that had to be fixed first", level=1)
    body(
        doc,
        "While building rainfall features, POWER precipitation summed to 197,188 mm over four years at "
        "Rajshahi — about 112 mm every day, including the dry season. Checking the same point and days "
        "against the live POWER API gave a daily value 24 times smaller, while the other seven "
        "parameters matched exactly:",
    )
    add_table(
        doc,
        ["Parameter", "Live POWER API", "Local CSV", "Ratio"],
        [
            ["T2M", "27.05 C", "27.05 C", "1.000"],
            ["T2M_MAX", "29.01 C", "29.01 C", "1.000"],
            ["T2M_MIN", "25.53 C", "25.53 C", "1.000"],
            ["RH2M", "93.79 %", "93.79 %", "1.000"],
            ["WS2M", "4.04 m/s", "4.04 m/s", "1.000"],
            ["ALLSKY_SFC_SW_DWN", "5.98 MJ/m2", "5.98 MJ/m2", "1.000"],
            ["PS", "100.34 kPa", "100.34 kPa", "1.000"],
            ["PRECTOTCORR", "77.41 mm", "1,857.84 mm", "24.000"],
        ],
        widths=[4.0, 3.2, 3.2, 2.2],
    )
    caption(
        doc,
        "Table 1. Northwest Rajshahi, 4 October 2023. 40 further samples across all seven regions and "
        "ten dates in every season gave a ratio of exactly 24.00, so this is a constant scaling error, "
        "not noise.",
    )
    body(
        doc,
        "The fix is mechanical: Data/power_corrected/ holds copies with PRECTOTCORR divided by 24 (the "
        "raw column is preserved beside it as PRECTOTCORR_raw), and the feature builder prefers those "
        "copies. Corrected annual totals now run from 1,710 mm at Rajshahi to 5,200 mm at Sylhet, in "
        "line with the satellite rainfall record. Anything previously computed from the original POWER "
        "files — irrigation demand in particular — should be recomputed.",
    )

    # 3 feature engineering
    doc.add_heading("3. How the features were built", level=1)
    for lead, text in [
        ("No future information. ", "Each row's features use data up to and including that day. Targets are shifted forward and are never filled."),
        ("Missing stays missing. ", "No zero-filling. Where a sparse satellite variable is carried forward it gets an age column and an observed-today flag, so a model can separate a fresh retrieval from a two-week-old one."),
        ("Bounded carry-forward. ", "HLS 45 days, ECOSTRESS 10, GRACE 60. Past the cap the value becomes null rather than being silently reused."),
        ("Time-based splits. ", "Train 2022-2024, validation 2025, test 2026. Daily environmental series are strongly autocorrelated, so a random split would leak the future."),
    ]:
        bullet(doc, text, lead=lead)

    add_table(
        doc,
        ["Feature family", "Examples", "Built from"],
        [
            ["Weather", "t2m_c, tmax_c, rh_pct, solar_mj_m2, pressure_kpa", "POWER (corrected)"],
            ["Derived meteorology", "et0_best_mm, vpd_kpa, gdd_base10, heat_day_35, diurnal_range_c", "FAO-56 Penman-Monteith; Hargreaves fallback"],
            ["Rainfall windows", "power_rain_sum_3d ... _90d, gpm_rain_sum_30d, dry_spell_days", "Rolling sums ending on the row date"],
            ["Soil moisture", "sm_mean, sm_7d_mean, sm_anomaly_30d, sm_obs_age_days", "SMAP AM/PM retrievals"],
            ["Vegetation", "ndvi_last, ndmi_last, hls_age_days", "HLS, carried at most 45 days"],
            ["Surface temperature", "lst_c_last, ecostress_age_days", "ECOSTRESS clear-sky overpasses"],
            ["Water storage", "grace_lwe_cm_last, grace_age_days", "GRACE mascon, 60-day carry"],
            ["Terrain", "elevation_mean_m, slope_mean_deg", "SRTM, static"],
            ["Calendar", "doy_sin, doy_cos, month, is_monsoon, season", "Derived; season follows the plan's boro/aman/rabi windows"],
        ],
        widths=[3.4, 7.6, 5.4],
    )
    caption(doc, "Table 2. The feature families in model_ready/. The full per-column dictionary is in feature_dictionary.csv.")
    body(
        doc,
        "Two derived variables deserve a note. ET0 is computed twice: the full FAO-56 Penman-Monteith "
        "equation where POWER supplies solar radiation, and a Hargreaves fallback where it does not "
        "(86 days per region). A flag records which was used, because the two are not interchangeable. "
        "VPD is derived from temperature and humidity rather than stored by any product.",
    )

    # 4 tables
    doc.add_heading("4. What is in model_ready/", level=1)
    add_table(
        doc,
        ["File", "Rows", "Contents"],
        [
            ["daily_panel.csv", f"{daily_rows:,}", f"7 regions x 1,759 days, {daily_cols} columns"],
            ["monthly_panel.csv", f"{monthly_rows}", f"7 regions x 58 months, {monthly_cols} columns"],
            ["feature_dictionary.csv", str(len(fdict)), "Every column: source, unit, meaning, leakage note"],
            ["data_quality_report.csv", str(len(daily_q)), "Completeness per column"],
            ["split_manifest.json", "-", "Train/valid/test boundaries"],
            ["baseline_results.json", "-", "Scores of the reference models"],
            ["README.md", "-", "Usage rules and caveats"],
        ],
        widths=[4.6, 1.8, 10.0],
    )
    caption(doc, "Table 3. Outputs of build_model_ready.py.")

    body(doc, "Targets available, with the number of rows that actually carry a value:")
    add_table(
        doc,
        ["Target", "Table", "Rows with a value", "Why it is useful"],
        [
            ["target_sm_next_day", "daily", "8,025", "Irrigation cue when no rover is in the field"],
            ["target_et0_next_day_mm", "daily", "12,285", "Water demand, feeding the engine's water balance"],
            ["target_rain_next_day_mm", "daily", "12,306", "Spray/fertiliser timing, dry-spell onset"],
            ["target_heat_next_day", "daily", "12,285", "Heat-stress warning"],
            ["ndvi_next_month", "monthly", "214", "Canopy trend for rotation comparison"],
        ],
        widths=[4.6, 1.6, 2.6, 7.6],
    )
    caption(doc, "Table 4. Prediction targets.")

    # 5 EDA findings
    doc.add_heading("5. What the exploratory analysis added", level=1)
    body(
        doc,
        "A separate pass over the raw CSVs (full detail in Data/_report/EDA.md) confirmed the "
        "precipitation defect independently and surfaced six more things that shape the feature design:",
    )
    for lead, text in [
        ("GPM changes run halfway through the record. ", "Final Run data ends on 2025-09-30 and the Late Run takes over; in June-August the Late Run reads 40-50% low against POWER. The panel therefore carries gpm_is_late_run so a model cannot mistake the run change for a climate trend."),
        ("The two rainfall sources disagree in ways worth keeping. ", "GPM and POWER correlate at r = 0.71 with a 37% monsoon bias, and diverge by 2-27x between November and February. They are kept as separate features, never averaged."),
        ("Almost half of all days are dry. ", "47.9% of GPM region-days are exactly 0.0 mm, so rainfall should be modelled as two parts - probability of rain, then amount given rain - rather than one squared-error regression."),
        ("Rainfall barely explains soil moisture once seasonality is removed. ", "The raw 0.30-0.39 correlation is shared annual cycle; deseasonalised, it falls to 0.14-0.21, and turns slightly negative from November to March. Soil moisture needs antecedent-precipitation windows, which is why the panel carries 30-, 60- and 90-day totals."),
        ("Vegetation observations are missing exactly when vegetation matters. ", "HLS yields an NDVI value in only 218 of 406 region-months, and availability is worst in June (20%) and August (26%) - the monsoon peak. A monthly NDVI series built from this will under-represent the growing season."),
        ("Autocorrelation limits the evaluation design. ", "Decorrelation time is about 4 days for rainfall, 12 for solar radiation and more than 30 for temperature, humidity, pressure and soil moisture. At 1,759 days the effective sample size for temperature is roughly 15. Any random split will report near-perfect scores; use forward-chaining with an embargo."),
    ]:
        bullet(doc, text, lead=lead)

    # 6 baselines
    doc.add_heading("6. Can these features predict anything?", level=1)
    body(
        doc,
        "train_baseline.py fits persistence and climatology baselines, then ridge and gradient boosting, "
        "on the time-based split. Reporting baselines beside the models matters: a model that cannot beat "
        "'tomorrow looks like today' has added nothing.",
    )
    rows = []
    labels = {
        "rain_next_day": "Rainfall, next day (mm)",
        "soil_moisture_next_day": "Soil moisture, next day (m3/m3)",
        "et0_next_day": "ET0, next day (mm)",
        "ndvi_next_month": "NDVI, next month",
    }
    for key, label in labels.items():
        res = baseline.get(key, {})
        if not res or "skipped" in res:
            continue
        for model in ("persistence", "climatology", "ridge", "gradient_boosting"):
            m = res.get(model)
            if not m:
                continue
            rows.append(
                [
                    label if model == "persistence" else "",
                    {"persistence": "persistence", "climatology": "climatology",
                     "ridge": "ridge", "gradient_boosting": "gradient boosting"}[model],
                    f"{m['mae']:.3f}",
                    f"{m['rmse']:.3f}",
                    f"{m['r2']:.2f}",
                ]
            )
    add_table(
        doc,
        ["Target", "Model", "MAE", "RMSE", "R2"],
        rows,
        widths=[5.6, 3.4, 2.2, 2.2, 2.0],
    )
    caption(
        doc,
        "Table 5. Test-period scores (2026 hold-out). Soil moisture and ET0 are clearly predictable; "
        "rainfall is not. The NDVI test set is only 26 monthly rows, and those are the months that "
        "happened to be clear, so the sample is selected on cloud cover.",
    )
    body(
        doc,
        "The honest reading: next-day soil moisture carries real skill (R2 "
        f"{baseline['soil_moisture_next_day']['gradient_boosting']['r2']:.2f} against "
        f"{baseline['soil_moisture_next_day']['persistence']['r2']:.2f} for persistence) because the "
        "surface retains water from one day to the next. ET0 is mostly seasonal but not only seasonal: "
        "the monthly cycle accounts for most of the variance, yet removing it still leaves the model "
        "ahead of persistence on daily data (R2 0.61 vs 0.51) - a one-day weather-persistence effect. At "
        "monthly aggregation that anomaly skill disappears entirely, so the scale has to be stated "
        "whenever this number is quoted. Rainfall one "
        "day ahead is close to noise at a point: the features describe the atmosphere's state, not its "
        "triggering. Any product built on this should present rainfall as climatological risk and current "
        "wetness, not as a deterministic forecast.",
    )

    # 6 screening
    doc.add_heading("7. What drives the signal", level=1)
    targets = screening.get("targets", {})
    rows = []
    for key, label in [
        ("A_next_month_ndvi", "NDVI, next month"),
        ("B_next_day_soil_moisture", "Soil moisture, next day"),
        ("C_next_day_rainfall_occurrence", "Rain occurrence, next day"),
        ("C_next_day_rainfall_amount", "Rain amount, next day"),
    ]:
        block = targets.get(key, {})
        feats = [f.get("feature") for f in block.get("top_features", [])][:5]
        seen = []
        for f in feats:
            if f and f not in seen:
                seen.append(f)
        rows.append([label, block.get("n_rows", "-"), ", ".join(seen[:5]) if seen else "n/a"])
    add_table(doc, ["Target", "Rows", "Strongest features"], rows, widths=[4.6, 1.6, 10.2])
    caption(doc, "Table 6. From the independent screening pass (Data/_report/feature_screening.json).")
    body(
        doc,
        "The pattern is consistent across targets and methods: recent wetness dominates. For soil "
        "moisture the previous days' retrievals carry almost all of the signal; for rainfall, the count "
        "of rainy days in the last week is the strongest single predictor; for monthly NDVI, temperature "
        "extremes and accumulated rainfall matter more than any instantaneous value. This is why the "
        "feature set leans on rolling windows rather than single-day snapshots.",
    )

    # 7 agrifusion
    doc.add_heading("8. Where this plugs into AgriFusionBD", level=1)
    body(
        doc,
        "The backend already has the right shape: apps/environment owns DatasetProduct, DataAsset and "
        "FieldIndicator, and apps/analyses/engine is a pure calculation layer that consumes an "
        "EngineInput. No new Django app is needed for any of these datasets.",
    )
    add_table(
        doc,
        ["Dataset", "Engine hook that exists", "What to extend"],
        [
            ["Rainfall", "PowerDay.prectot -> _effective_rain (water_balance.py)", "accept a GPM series as an alternative source"],
            ["Soil moisture", "soil bucket starts full (water_balance.py:67)", "initialise the bucket from SMAP; gate dry_spell_days"],
            ["Land-surface temperature", "heat.py uses air tmax only", "add lst to PowerDay and use it in season_heat"],
            ["Terrain", "elevation_m is accepted but never passed", "pass SRTM elevation at water_balance.py:75; slope into bucket capacity"],
            ["Water storage", "none", "new indicator kind; initialise bucket from GRACE"],
            ["Vegetation", "cover.py takes NDVI + coverage", "add NDMI alongside NDVI"],
        ],
        widths=[3.4, 6.4, 6.6],
    )
    caption(doc, "Table 7. Dataset-to-engine mapping. Full detail with line references is in Data/_report/agrifusion_map.md.")

    body(doc, "The shortest path to visible progress, in order:")
    for i, (lead, text) in enumerate(
        [
            ("Extend the indicator kinds. ", "Add soil_moisture, land_surface_temperature, ndmi, water_storage, elevation and slope to FieldIndicator.KIND_CHOICES, then migrate."),
            ("Write one service per source. ", "Copy the shape of environment/services/power.py: product, content-hashed asset, indicators, nulls for gaps."),
            ("Thread one dataset through the engine first. ", "Soil moisture into water_balance is the highest-value change: it turns a bucket that starts full into one grounded in observation."),
            ("Version the rules. ", "If a metric definition changes, bump RULE_VERSION so old analyses stay explainable."),
        ],
        start=1,
    ):
        bullet(doc, text, lead=f"{i}. {lead}")

    # 8 hazards
    doc.add_heading("9. Problems in the current backend worth fixing", level=1)
    body(
        doc,
        "Found by reading the repository, not by running it. They matter because new data sources will "
        "copy these patterns.",
    )
    for lead, text in [
        ("ET0 is labelled FAO-56 but is not. ", "engine/et0.py builds net longwave from |T - 273|^4 and ignores humidity; the correct series in model_ready/ can replace it. Irrigation demand inherits the error."),
        ("Power indicator persistence looks broken. ", "_store_indicators omits period_end while the column is non-null with no default; a fresh live fetch would fail on the first insert."),
        ("NDVI never reaches the API. ", "The HLS service writes a DataAsset but no FieldIndicator rows, so vegetation data exists but is not queryable through the indicators endpoint."),
        ("The asset cache key excludes the field. ", "DataAsset.cache_key is globally unique and field-free while DataAsset.field records only the first caller, so per-field provenance can point at another field's asset."),
        ("Engine tests assert on wording. ", "A water-balance qualification must contain 'uncertainty' or 'not zero', so rewording breaks tests."),
        ("Metric keys are coupled in four places. ", "A key missing from rules.BOUNDS silently normalises to zero instead of raising."),
    ]:
        bullet(doc, text, lead=lead)

    # 9 reproduce
    doc.add_heading("10. Reproducing this", level=1)
    body(doc, "All scripts live in Data/ and run with Data/.venv:")
    add_table(
        doc,
        ["Script", "Does"],
        [
            ["fix_power_precip.py", "writes corrected POWER copies (PRECTOTCORR / 24)"],
            ["build_model_ready.py", "builds both panels, the dictionary and the quality report"],
            ["train_baseline.py", "fits baselines and models, writes baseline_results.json"],
            ["report_stats.py / report_figures.py", "statistics and figures for the data report"],
            ["build_report_docx.py", "builds NASA_Data_Report.docx"],
        ],
        widths=[5.0, 11.0],
    )
    caption(doc, "Table 8. Pipeline scripts. All are idempotent.")

    p = doc.add_paragraph()
    r = p.add_run(
        "Caveat that applies to every number here: the record is under five years, the seven points are "
        "single coordinates, and nothing in these tables is a measurement at a farm. They are regional "
        "context, modelled and re-sampled, and should be labelled as such wherever they are shown."
    )
    r.font.size = Pt(9)
    r.font.color.rgb = MUTED

    doc.save(OUT_PATH)
    print(f"Saved {OUT_PATH} ({OUT_PATH.stat().st_size / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
